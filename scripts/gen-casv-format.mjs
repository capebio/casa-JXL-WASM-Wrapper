#!/usr/bin/env node
/**
 * gen-casv-format.mjs — Single Source of Truth generator for CASV format constants.
 *
 * Reads `pub const CASV_*` from crates/raw-pipeline/src/casa_video.rs (the Rust
 * reference implementation) and emits two artefacts:
 *
 *   1. casv-format.json         (repo root) — cross-language SSoT used by parity tests
 *   2. packages/casv-web/src/casv-format.ts — typed TS module imported by casv-web
 *
 * Usage:
 *   node scripts/gen-casv-format.mjs
 *
 * Run this whenever casa_video.rs constants change, then commit both artefacts.
 * The parity test (packages/casv-web/test/casv-format-parity.test.ts) will fail
 * if the casv-web TS exports drift from casv-format.json.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join, dirname } from "node:path";

const __dir = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dir, "..");

// ── Parse Rust source ────────────────────────────────────────────────────────

const rustSrc = readFileSync(
  join(repoRoot, "crates/raw-pipeline/src/casa_video.rs"),
  "utf8"
);

/** Parse a hex literal (0x…) or decimal literal from Rust const. */
function parseValue(s) {
  const clean = s.replace(/_/g, ""); // Rust allows _ in numeric literals
  if (clean.startsWith("0x") || clean.startsWith("0X")) {
    return parseInt(clean, 16);
  }
  return parseInt(clean, 10);
}

/**
 * Match `pub const CASV_<NAME>: <type> = <value>;` lines.
 * Skips `const CASV_FLAG_BITS` (derived, not part of the public SSoT).
 */
const CONST_RE =
  /^pub\s+const\s+(CASV_[A-Z0-9_]+)\s*:\s*\S+\s*=\s*(0x[0-9a-fA-F_]+|\d[\d_]*)\s*;/gm;

const constants = {};
for (const m of rustSrc.matchAll(CONST_RE)) {
  const name = m[1];
  const raw = m[2];
  constants[name] = parseValue(raw);
}

// Validate we found the expected set of constants (catches renames in Rust).
const EXPECTED = [
  "CASV_MAGIC",
  "CASV_VERSION",
  "CASV_HEADER_BYTES",
  "CASV_INDEX_ENTRY_BYTES",
  "CASV_PFRAME_FLAG",
  "CASV_BBOX_FLAG",
  "CASV_TILE_FLAG",
  "CASV_REPLACE_FLAG",
  "CASV_HDR_FABLE_FLAG",
  "CASV_TILE_V2_BIT",
  "CASV_HDRFLAG_LOSSY",
  "CASV_FOOTER_MAGIC",
  "CASV_FOOTER_BYTES",
  "CASV_AUDIO_BOX_MAGIC",
  "CASV_RATE_BOX_MAGIC",
];

const missing = EXPECTED.filter((k) => !(k in constants));
if (missing.length) {
  console.error(`ERROR: missing constants in casa_video.rs: ${missing.join(", ")}`);
  process.exit(1);
}

// Keep only the 15 public CASV_ constants in definition order.
const ordered = {
  _source:
    "crates/raw-pipeline/src/casa_video.rs — CASAVA (.casv) container constants. " +
    "K6#3 single source of truth: crates/raw-pipeline tests pin the Rust consts to " +
    "this file; packages/casv-web tests pin the TS consts to it. " +
    "A drift on either side fails its parity test.",
};
for (const k of EXPECTED) {
  ordered[k] = constants[k];
}

// ── Emit casv-format.json (repo root) ────────────────────────────────────────

const jsonPath = join(repoRoot, "casv-format.json");
writeFileSync(jsonPath, JSON.stringify(ordered, null, 2) + "\n", "utf8");
console.log(`wrote ${jsonPath}`);

// ── Emit packages/casv-web/src/casv-format.ts ────────────────────────────────
//
// This is a GENERATED file — do not edit by hand.  Re-run gen-casv-format.mjs.

const tsLines = [
  "// GENERATED by scripts/gen-casv-format.mjs — do not edit by hand.",
  "// Source of truth: crates/raw-pipeline/src/casa_video.rs",
  "// Re-run `node scripts/gen-casv-format.mjs` after changing Rust constants.",
  "",
];

for (const [name, value] of Object.entries(ordered)) {
  // Skip non-constant annotation keys (e.g. _source).
  if (!name.startsWith("CASV_")) continue;
  // Emit hex literals for magic/flag values; decimal for byte-count / version.
  const isByteCount = name.endsWith("_BYTES") || name === "CASV_VERSION";
  const lit = isByteCount ? String(value) : `0x${value.toString(16).toUpperCase().padStart(8, "0")}`;
  tsLines.push(`export const ${name} = ${lit};`);
}
tsLines.push("");

const tsPath = join(repoRoot, "packages/casv-web/src/casv-format.ts");
writeFileSync(tsPath, tsLines.join("\n"), "utf8");
console.log(`wrote ${tsPath}`);
